const QINGLONG_START: Record<string, string> = {
  子: '申', 午: '申',
  寅: '子', 申: '子',
  卯: '寅', 酉: '寅',
  辰: '辰', 戌: '辰',
  巳: '午', 亥: '午',
  丑: '戌', 未: '戌',
}

export const ZHI_ORDER = ['子', '丑', '寅', '卯', '辰', '巳', '午', '未', '申', '酉', '戌', '亥'] as const

export function hourGods(dayZhi: string): Array<{ zhi: string; god: God; lucky: boolean; note: string }> {
  const start = QINGLONG_START[dayZhi] ?? '子'
  const si = ZHI_ORDER.indexOf(start as never)
  const out: Array<{ zhi: string; god: God; lucky: boolean; note: string }> = []
  const LUCKY = new Set<string>(['青龙', '明堂', '金匮', '天德', '玉堂', '司命'])
  for (let i = 0; i < 12; i++) {
    const zhi = ZHI_ORDER[(si + i) % 12]!
    const god = GODS[i]!
    out.push({ zhi, god, lucky: LUCKY.has(god), note: GOD_NOTE[god] })
  }
  return out
}
