const STORAGE_KEY = 'bs-theme'

export function currentThemeId(): string {
  return localStorage.getItem(STORAGE_KEY) ?? 'zixiao'
}

function injectStyles(): void {
  if (document.getElementById('bs-themes')) return
  const css = THEMES.filter((t) => t.vars && Object.keys(t.vars).length > 0)
    .map((t) => `html[data-theme='${t.id}']{${Object.entries(t.vars).map(([k, v]) => `${k}:${v}`).join(';')}}`)
    .join('\n')
  const style = document.createElement('style')
  style.id = 'bs-themes'
  style.textContent = css
  document.head.appendChild(style)
}

/** 应用主题；非法 id 回退到默认 */
export function applyTheme(id: string): string {
  const def = THEMES.find((t) => t.id === id)
  if (!def || Object.keys(def.vars).length === 0) {
    delete document.documentElement.dataset.theme
    localStorage.removeItem(STORAGE_KEY)
    return 'zixiao'
  }
  document.documentElement.dataset.theme = def.id
  localStorage.setItem(STORAGE_KEY, def.id)
  return def.id
}

/** 启动时调用：注入全部皮肤样式并恢复上次选择 */
export function initThemes(): void {
  injectStyles()
  applyTheme(currentThemeId())
}
