export function lookup(term: string): GlossaryEntry | null {
  if (GLOSSARY[term]) return GLOSSARY[term]
  const hit = ALIAS[term]
  return hit ? GLOSSARY[hit] ?? null : null
}

export interface Segment { text: string; term?: string }

const TERM_KEYS = [...Object.keys(GLOSSARY), ...Object.keys(ALIAS)].sort((a, b) => b.length - a.length)
const TERM_RE = new RegExp(`(${TERM_KEYS.map((k) => k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|')})`, 'g')

/** 把一段白话按术语切成段，命中处交给 TermTip 渲染 */
export function segmentTerms(text: string): Segment[] {
  const out: Segment[] = []
  let last = 0
  for (const m of text.matchAll(TERM_RE)) {
    const at = m.index ?? 0
    if (at > last) out.push({ text: text.slice(last, at) })
    out.push({ text: m[0], term: m[0] })
    last = at + m[0].length
  }
  if (last < text.length) out.push({ text: text.slice(last) })
  return out
}
